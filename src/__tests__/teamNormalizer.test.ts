import { describe, it, expect } from 'vitest';
import { normalizeTeamName } from '../utils/teamNormalizer';

describe('normalizeTeamName', () => {
  it.each([
    // Empty and basic inputs
    ['', ''],
    ['   ', ''],
    ['מכבי חיפה', 'מכבי חיפה'],
    [' מכבי חיפה ', 'מכבי חיפה'],

    // Special characters removal (quotes, dots, minuses)
    ['מכבי "חיפה"', 'מכבי חיפה'],
    ["מכבי 'חיפה'", 'מכבי חיפה'],
    ['מכבי ״חיפה״', 'מכבי חיפה'],
    ['מכבי ׳חיפה׳', 'מכבי חיפה'],
    ['מ.ס. חיפה', 'מס חיפה'],
    ['מכבי-חיפה', 'מכבי חיפה'],

    // Specific team logic
    ['מכבי תל אביב', 'מכבי תא'],
    ['הפועל תל אביב', 'הפועל תא'],
    ['בני יהודה תל אביב', 'בני יהודה תא'],

    ['הפועל באר שבע', 'הפועל בש'],
    ['מכבי באר שבע', 'מכבי בש'],

    ['עירוני קרית שמונה', 'עירוני קש'],
    ['הפועל קרית שמונה', 'הפועל קש'],

    ['מכבי פתח תקוה', 'מכבי פת'],
    ['הפועל פתח תקווה', 'הפועל פת'],

    ['בני ריינה', 'מכבי בני ריינה'],
    ['מכבי בני ריינה', 'מכבי בני ריינה'],

    ['מ.ס. אשדוד', 'מס אשדוד'],
    ['הפועל אשדוד', 'מס אשדוד'],

    ['עירוני טבריה', 'עירוני טבריה'],
    ['הפועל טבריה', 'עירוני טבריה'],

    ['בני סכנין', 'בני סכנין'],
    ['הפועל סכנין', 'בני סכנין'],

    ['מכבי נתניה', 'מכבי נתניה'],
    ['מכבי עירוני נתניה', 'מכבי נתניה'],
    ['הפועל נתניה', 'הפועל נתניה'], // Doesn't have מכבי

    ['הפועל חדרה', 'הפועל חדרה'],
    ['מכבי חדרה', 'הפועל חדרה'],

    // Mixed conditions and extra spaces
    ['  מכבי   תל    אביב  ', 'מכבי תא'],
    ['מ.ס.   אשדוד', 'מס אשדוד'],
    ['מכבי-תל-אביב', 'מכבי תא'],
    ['מכבי "תל-אביב"', 'מכבי תא'],

    // English/Case handling (though mostly Hebrew is used)
    ['Maccabi Haifa', 'maccabi haifa'],
    ['MACCABI HAIFA', 'maccabi haifa']

  ])('should normalize "%s" to "%s"', (input, expected) => {
    expect(normalizeTeamName(input)).toBe(expected);
  });
});
